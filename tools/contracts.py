def _refs(node, acc):
    if isinstance(node, dict):
        r = node.get("$ref")
        if isinstance(r, str) and r.startswith("#/$defs/"):
            acc.add(r.split("/")[-1])
        for v in node.values():
            _refs(v, acc)
    elif isinstance(node, list):
        for v in node:
            _refs(v, acc)
    return acc


def closure(names):
    """Transitive $defs closure, so each emitted schema is self-contained."""
    seen, todo = set(), list(names)
    while todo:
        n = todo.pop()
        if n in seen:
            continue
        seen.add(n)
        todo.extend(_refs(DEFS[n], set()) - seen)
    return seen


