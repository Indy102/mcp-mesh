def output_schema(tool):
    """Self-contained outputSchema: oneOf(success, ErrorPayload). No non-local $ref."""
    need = closure([SUCCESS[tool], "ErrorPayload"])
    # `type: object` is required at the root: the MCP Python SDK's Tool.outputSchema
    # model rejects a schema whose root has only `oneOf` (discovered by running the SDK,
    # not by reading the spec — plain JSON Schema would accept it). Every payload is an
    # object, so this is a true narrowing, not a workaround.
    return {"$schema": "https://json-schema.org/draft/2020-12/schema",
            "title": f"{tool} result",
            "type": "object",
            "$defs": {k: DEFS[k] for k in sorted(need)},
            "oneOf": [{"$ref": f"#/$defs/{SUCCESS[tool]}"},
                      {"$ref": "#/$defs/ErrorPayload"}]}


