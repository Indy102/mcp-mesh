def semantic_errors(name, args):
    """Named cross-field rules JSON Schema cannot express, enforced at every server
    boundary. These live with the contracts, not inside one server, because they are
    part of the declared input contract for the tool wherever it is served."""
    def rng(k):
        v = args.get(k)
        return (v.get("start"), v.get("end")) if isinstance(v, dict) else None
    if name == "compare_periods":
        a, b = rng("period_a"), rng("period_b")
        for label, r in (("period_a", a), ("period_b", b)):
            if r and r[0] and r[1] and r[0] > r[1]:
                return f"{label}.start must not be after {label}.end (SI-1)"
        if a and b and a[0] and a[1] and b[0] and b[1] and a[0] <= b[1] and b[0] <= a[1]:
            return "period_a and period_b must not overlap (SI-2)"
    if name == "fetch":
        s, e = args.get("start"), args.get("end")
        if s and e and s > e:
            return "start must not be after end (SI-1)"
    return None
